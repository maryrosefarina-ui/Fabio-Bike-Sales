-- =================
-- Date Exploration
-- =================

-- Find the date of the first and last order
-- How many years of sales are available
	SELECT 
		MIN(order_date) AS first_order, 
		MAX(order_date) last_order,
		DATEDIFF(YEAR, MIN(order_date), MAX(order_date)) AS interval_order_years
	FROM retail.fact_sales

-- Find the youngest and oldest customers
	SELECT 
		MIN(birthdate) AS oldest_birthdate,
		DATEDIFF(YEAR, MIN(birthdate), GETDATE()) AS oldest_customer,
		MAX(birthdate) AS youngest_birthdate,
		DATEDIFF(YEAR, MAX(birthdate), GETDATE()) AS youngest_customer
	FROM retail.dim_customers

