-- Magnitude Analysis 
-- ===================

-- Measures by Dimensions
-- Find total customers by countries
	SELECT country, COUNT(customer_id) AS total_customers
	FROM retail.dim_customers
	GROUP BY country
	ORDER BY total_customers DESC

-- Find total customers by gender
	SELECT * FROM gold.dim_customers;
	SELECT gender, COUNT(customer_id) AS total_customers 
	FROM retail.dim_customers
	GROUP BY gender 
	ORDER BY total_customers DESC

-- Find total products by category
	SELECT category, COUNT(product_name) AS total_products
	FROM retail.dim_products
	GROUP BY category
	ORDER BY category DESC

-- What is the average costs in each category?
	SELECT category, AVG(cost) avg_cost 
	FROM retail.dim_products
	GROUP BY category
	ORDER BY avg_cost DESC

-- What is the total revenue generated for each category?
	SELECT dp. category, SUM(fs.sales_amount) AS total_revenue
	FROM retail.fact_sales AS fs
	LEFT JOIN retail.dim_products AS dp
		ON fs.product_key = dp.product_key
	GROUP BY dp.category
	ORDER BY total_revenue DESC

-- Find the total revenue is generated by each customer
	SELECT dc.customer_id, dc.first_name, dc.last_name,
	SUM(sales_amount) AS total_revenue
	FROM retail.fact_sales AS fs
	JOIN retail.dim_customers AS dc
		ON fs.customer_key = dc.customer_key
	GROUP BY dc.customer_id, dc.first_name, dc.last_name
	ORDER BY total_revenue DESC

-- What is the distribution of sold items across countries?
	SELECT dc.country, SUM(fc.quantity) AS total_sold_items
	FROM retail.fact_sales AS fc
	INNER JOIN retail.dim_customers AS dc
		ON fc.customer_key = dc.customer_key
	GROUP BY dc.country
	ORDER BY total_sold_items DESC

-- =================
-- Ranking Analysis
-- =================

-- Using Window Functions
-- Find the Top 10 customers who have generated the highest revenue
	SELECT *
	FROM(
	SELECT dc.customer_key, dc.first_name, dc.last_name,
	SUM(sales_amount) AS total_revenue,
	RANK() OVER(ORDER BY SUM(sales_amount) DESC) AS rank_sales
	FROM retail.dim_customers AS dc
	LEFT JOIN retail.fact_sales AS fs
		ON dc.customer_key = fs.customer_key
	GROUP BY dc.customer_key, dc.first_name, dc.last_name
	) AS Top_Ten_Customers_High_Rev
	WHERE rank_sales <= 10

-- Find 3 customers with the fewest orders placed
	SELECT TOP 3 dc.customer_key, dc.first_name, dc.last_name,
	COUNT(DISTINCT fs.order_number) AS total_orders
	FROM retail.dim_customers AS dc
	LEFT JOIN retail.fact_sales AS fs
		ON dc.customer_key = fs.customer_key
	GROUP BY dc.customer_key, dc.first_name, dc.last_name
	ORDER BY total_orders ASC